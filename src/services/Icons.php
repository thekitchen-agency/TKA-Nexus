    public function getAvailableIcons(): array
    {
        return $this->_builtInIcons;
    }

    public function render(string $name, array $options = []): string
    {
        $svg = $this->_builtInIcons[$name] ?? null;

        if (!$svg) {
            // Check project @webroot/icons or custom folder
            $customPath = Craft::getAlias('@webroot/icons/' . $name . '.svg', false);
            if ($customPath && file_exists($customPath)) {
                $svg = file_get_contents($customPath);
            }
        }

        if (!$svg) {
            return '';
        }

        if (!empty($options['class'])) {
            $svg = preg_replace('/<svg /', '<svg class="' . htmlspecialchars($options['class'], ENT_QUOTES) . '" ', $svg, 1);
        }

        return $svg;
    }
